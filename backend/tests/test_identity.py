import pytest

from app.domain.identity import normalize_identity
from app.infrastructure.passwords import verify_password


@pytest.mark.parametrize(
    "source,expected",
    [
        ("  Jose\u0301\u00a0 da\tSilva  ", "JOSÉ DA SILVA"),
        ("straße", "STRASSE"),
        ("ana-maria d'ávila", "ANA-MARIA D'ÁVILA"),
    ],
)
def test_normalization_preserves_accents(source, expected):
    assert normalize_identity(source) == expected


def test_invisible_controls_rejected():
    with pytest.raises(ValueError):
        normalize_identity("ANA\u200bMARIA")


def test_scrypt_compatibility_preserves_password_whitespace():
    password = " Senha sintética Ç "
    salt = "synthetic-salt"
    # Independent vector generated by Node 22 scryptSync(password, salt, 64).
    expected = (
        "df0db0e051dc40ae2a6c0712bf7a037da49bb5e2060b536032d6df7acf6949e4"
        "67861e8251ed63d71ea25e0fdaaa9f7cb806804d08d2bddec254aa8e68bf30de"
    )
    assert verify_password(password, salt + ":" + expected)
    assert not verify_password(password.strip(), salt + ":" + expected)
    assert not verify_password(password, "plaintext")
