from contextlib import AbstractContextManager
from datetime import datetime
from typing import Any, Protocol


class AuthWork(Protocol):
    def lock_attempt(self, key: str) -> None: ...
    def get_attempt(self, key: str) -> Any: ...
    def save_attempt(
        self, key: str, failures: int, first: datetime, locked: datetime | None
    ) -> None: ...
    def clear_attempt(self, key: str) -> None: ...
    def find_professionals(self, email: str) -> list: ...
    def find_professional(self, professional_id: str) -> Any: ...
    def teams(self, professional_id: str) -> tuple[str, ...]: ...
    def create_session(self, token_hash: str, professional_id: str, expires: datetime) -> None: ...
    def session_professional(self, token_hash: str) -> str | None: ...
    def delete_session(self, token_hash: str) -> None: ...


class AuthRepository(Protocol):
    def unit_of_work(self, *, readonly: bool = False) -> AbstractContextManager[AuthWork]: ...


class RegistryRepository(Protocol):
    def search(self, clinic_id: str, normalized: str, user_id: str | None, offset: int) -> list: ...
